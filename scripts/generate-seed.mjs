// Builds supabase/seed.sql from content/team.json so the existing site content
// (six players, their portraits, team identity, kit artwork and gallery) moves into
// Supabase unchanged. Every statement is idempotent: re-running it never duplicates or
// overwrites records that an administrator has since edited.
//
// Usage: node scripts/generate-seed.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const team = JSON.parse(readFileSync(join(root, "content/team.json"), "utf8"));

// Pixel sizes of the artwork shipped in public/images (player portraits are the
// Real-ESRGAN upscales, named -hd so no cache serves the old low-resolution files).
const sizes = {
  "player-01-hd.webp": [1590, 2226],
  "player-02-hd.webp": [1788, 2236],
  "player-03-hd.webp": [1688, 2364],
  "player-04-hd.webp": [1688, 2364],
  "player-05-hd.png": [1713, 2379],
  "player-06-hd.webp": [1688, 2364],
  "team-kit-v2.webp": [1900, 1106],
};
// Portraits photographed on black rather than cut out (none: every portrait is now transparent).
const onBlack = new Set();

const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const slugify = (s) =>
  String(s).toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const lines = [];
lines.push("-- Generated by scripts/generate-seed.mjs from content/team.json. Safe to run more than once.");
lines.push("begin;");
lines.push("");

const social = (k) => {
  const v = (team.socials?.[k] ?? "").trim();
  return v.startsWith("https://") ? q(v) : "null";
};
const email = (team.email ?? "").trim();

lines.push("-- Team identity");
lines.push(
  `insert into public.team_settings (id, team_name, game, tagline, description, contact_email, site_url,
  facebook_url, instagram_url, youtube_url, tiktok_url, discord_url,
  hero_subtitle, statement, footer_description, about_lead, about_body)
values (1, ${q(team.teamName)}, ${q(team.game)}, ${q(team.tagline)}, ${q(team.description)}, ${q(email || null)}, ${q(team.siteUrl ?? null)},
  ${social("facebook")}, ${social("instagram")}, ${social("youtube")}, ${social("tiktok")}, ${social("discord")},
  'Six players in one black and violet kit, built to outlast every zone.',
  'Epic Elites is a Free Fire team built on trust in the lineup, hours of practice and a standard that rises every match. The name on the jersey is a promise we play to keep.',
  ${q(`${team.teamName} is a ${team.game} esports team. Roster, fixtures and team news live here.`)},
  ${q(`${team.teamName} competes in ${team.game} with one lineup, one kit and one standard.`)},
  'This site is where the team keeps its roster, fixtures, media and official news. As the team grows, it records the players and the matches that shape the name.')
on conflict (id) do nothing;`,
);
lines.push("");

lines.push("-- Players (portraits stay in public/images). A player that already exists, by slug or by");
lines.push("-- legacy number, is skipped: an admin may have renamed the slug since the first run.");
team.players.forEach((p, i) => {
  const [w, h] = sizes[p.image] ?? [null, null];
  const slug = slugify(`player-${p.number}`) || `player-${i + 1}`;
  lines.push(
    `insert into public.players (slug, legacy_key, display_name, role, jersey_number, bio, photo_url, photo_width, photo_height, photo_on_black, display_order)
values (${q(slug)}, ${q(p.number)}, ${q(p.name)}, ${q(p.role)}, ${q(/^\d{1,3}$/.test(p.number) ? p.number : null)}, ${q(p.bio)}, ${q(`/images/${p.image}`)}, ${w ?? "null"}, ${h ?? "null"}, ${onBlack.has(p.image)}, ${i + 1})
on conflict do nothing;`,
  );
});
lines.push("");

lines.push("-- Gallery: the kit image and every player portrait, published as they are today.");
lines.push(
  `insert into public.media_items (kind, category, title, caption, alt_text, url, width, height, is_published, display_order)
select 'image', 'kit', 'Team kit', 'Team kit, front and back', 'Epic Elites jersey shown front and back on mannequins',
       '/images/team-kit-v2.webp', 1900, 1106, true, 0
where not exists (select 1 from public.media_items where url = '/images/team-kit-v2.webp');`,
);
team.players.forEach((p, i) => {
  const [w, h] = sizes[p.image] ?? [null, null];
  const slug = slugify(`player-${p.number}`) || `player-${i + 1}`;
  lines.push(
    `insert into public.media_items (kind, category, alt_text, url, width, height, on_black, is_published, display_order, player_id)
select 'image', 'players', ${q(`${p.name} in the Epic Elites jersey`)}, ${q(`/images/${p.image}`)}, ${w ?? "null"}, ${h ?? "null"}, ${onBlack.has(p.image)}, true, ${i + 1},
       (select id from public.players where slug = ${q(slug)})
where not exists (select 1 from public.media_items where url = ${q(`/images/${p.image}`)});`,
  );
});
lines.push("");

lines.push("-- The kit announcement that used to be hard-coded on /news. It is kept as a DRAFT with no");
lines.push("-- publication date: publish it from the dashboard if and when the team wants it public.");
lines.push(
  `insert into public.news_posts (slug, title, summary, body, cover_url, cover_alt, category, status)
values ('the-epic-elites-kit-is-here', 'The Epic Elites kit is here',
  'Black body, violet piping and the winged crest. See the jersey from every angle and the players already wearing it.',
  ${q(
    "The official Epic Elites jersey pairs a black body with violet piping and angular panels.\n\nThe winged EE crest sits over the heart, the monogram opposite, and Rise Above runs down the side panel. On the back, every player's tag and number sit across the shoulders.\n\n[See the kit from every angle](/media)",
  )},
  '/images/team-kit-v2.webp', 'The Epic Elites jersey, front and back', 'official_announcements', 'draft')
on conflict (slug) do nothing;`,
);
lines.push("");

if ((team.upcomingMatches?.length ?? 0) + (team.results?.length ?? 0) > 0) {
  lines.push("-- content/team.json lists fixtures with free-text dates. They are not imported automatically");
  lines.push("-- because a wrong timestamp would publish a wrong schedule. Re-enter them in /EEAUTHOR/matches.");
}

lines.push("commit;");
writeFileSync(join(root, "supabase/seed.sql"), lines.join("\n") + "\n");
console.log("Wrote supabase/seed.sql");
