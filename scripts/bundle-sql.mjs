// Concatenates every migration plus the seed into supabase/setup-all.sql, so a hosted
// project can be set up by pasting one file into the Supabase SQL Editor.
// Usage: npm run sql:bundle

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase/migrations");
const parts = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8")}`);
parts.push(`-- ===== seed.sql =====\n${readFileSync(join(root, "supabase/seed.sql"), "utf8")}`);

writeFileSync(
  join(root, "supabase/setup-all.sql"),
  `-- Generated by scripts/bundle-sql.mjs. Paste into the Supabase SQL Editor and run.\n-- Safe to run again: existing tables, policies, triggers and seeded content are kept, not duplicated.\n\n${parts.join("\n\n")}`,
);
console.log("Wrote supabase/setup-all.sql");
