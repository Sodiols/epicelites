import type { Metadata } from "next";

const SITE_NAME = "Epic Elites";

/**
 * Metadata for a public page: unique title and description, canonical URL, and matching
 * Open Graph / Twitter cards. The share image comes from the opengraph-image file in the
 * page's route folder (a branded preview generated per page).
 */
export function pageMetadata({
  title,
  description,
  path,
  noindex = false,
}: {
  title: string;
  description: string;
  path: string;
  noindex?: boolean;
}): Metadata {
  const fullTitle = `${title} | ${SITE_NAME}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      title: fullTitle,
      description,
      url: path,
    },
    twitter: { card: "summary_large_image", title: fullTitle, description },
    ...(noindex ? { robots: { index: false, follow: true } } : {}),
  };
}
